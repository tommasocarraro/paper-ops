#!/usr/bin/env node
// make-table.mjs — CSV → booktabs tabular, so no result is typed by hand.
//
//   node make-table.mjs data.csv [--out table.tex] [--lower "col,col"]
//                                [--second] [--no-best]
//
// First column is the row label; the first row is the header. Cell text is
// copied unchanged: digits, precision and trailing zeros are never altered.
// The best value of each numeric column is set in bold (highest, or lowest for
// columns named in --lower); ties are all marked. --second also underlines the
// runner-up. A column is numeric when every non-empty cell parses as a number
// (a trailing % is allowed); other columns are left alone.
// Emits the tabular only: the table environment, caption and label belong in
// the section file. Exit 2 on usage errors.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const valueFlags = ['--out', '--lower'];
const input = args.find((a, i) => !a.startsWith('--') && !valueFlags.includes(args[i - 1]));

if (!input || !existsSync(input)) {
  console.error('usage: node make-table.mjs data.csv [--out table.tex] [--lower "col,col"] [--second] [--no-best]');
  process.exit(2);
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i += 1; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((r) => r.some((x) => x.trim() !== ''));
}

const escapeTex = (s) => s.trim().replace(/([&%#_$])/g, '\\$1');
const toNumber = (s) => {
  const t = s.trim().replace(/%$/, '');
  return /^[-+]?(\d+\.?\d*|\.\d+)$/.test(t) ? Number(t) : NaN;
};

const rows = parseCsv(readFileSync(input, 'utf8'));
if (rows.length < 2) {
  console.error(`${input}: need a header row and at least one data row`);
  process.exit(2);
}
const [header, ...body] = rows;
const width = header.length;
const ragged = body.findIndex((r) => r.length !== width);
if (ragged >= 0) {
  console.error(`${input}: row ${ragged + 2} has ${body[ragged].length} cells, header has ${width}`);
  process.exit(2);
}

const lower = new Set((option('--lower') ?? '').split(',').map((s) => s.trim()).filter(Boolean));
const unknown = [...lower].filter((name) => !header.map((h) => h.trim()).includes(name));
if (unknown.length) {
  console.error(`--lower names columns that are not in the header: ${unknown.join(', ')}`);
  process.exit(2);
}

// For each numeric column, the best and second-best distinct values.
const marks = header.map((name, col) => {
  if (col === 0 || flag('--no-best')) return null;
  const cells = body.map((r) => r[col]).filter((c) => c.trim() !== '');
  const values = cells.map(toNumber);
  if (!values.length || values.some(Number.isNaN)) return null;
  const distinct = [...new Set(values)].sort((a, b) => (lower.has(name.trim()) ? a - b : b - a));
  return { best: distinct[0], second: distinct.length > 1 ? distinct[1] : undefined };
});

const lines = [];
lines.push(`% Generated by make-table.mjs from ${input.split('/').pop()} — edit the CSV, not this file.`);
lines.push(`\\begin{tabular}{l${'c'.repeat(width - 1)}}`);
lines.push('\\toprule');
lines.push(`${header.map(escapeTex).join(' & ')} \\\\`);
lines.push('\\midrule');
for (const r of body) {
  const cells = r.map((raw, col) => {
    const text = escapeTex(raw);
    const mark = marks[col];
    if (!mark || raw.trim() === '') return text;
    const value = toNumber(raw);
    if (value === mark.best) return `\\textbf{${text}}`;
    if (flag('--second') && value === mark.second) return `\\underline{${text}}`;
    return text;
  });
  lines.push(`${cells.join(' & ')} \\\\`);
}
lines.push('\\bottomrule');
lines.push('\\end{tabular}');

const out = option('--out');
if (out) {
  writeFileSync(out, `${lines.join('\n')}\n`);
  console.log(`wrote ${out} (${body.length} rows, ${width} columns)`);
} else {
  console.log(lines.join('\n'));
}
